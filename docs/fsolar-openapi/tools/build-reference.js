#!/usr/bin/env node
// Converts the Apipost share payloads (/doc/preview + /doc/details) into REFERENCE.md.
const fs=require('fs');
const [,, previewPath, detailsPath, outPath] = process.argv;
if (!outPath) { console.error('usage: node build-reference.js <preview.json> <details.json> <out.md>'); process.exit(1); }
const load=p=>{const j=JSON.parse(fs.readFileSync(p,'utf8')); return j.data||j;};
const P=load(previewPath), D=load(detailsPath).list;
// Apipost labels left in Chinese by the authors
const ZH={'成功':'Success','失败':'Fail','授权失败':'Unauthorized','设备SN':'Device SN','响应码':'Response code','响应消息体':'Response message','返回数据':'Returned data','默认服务':'Default service','已完成':'Completed','开发中':'In Progress','需修改':'To Revise','已废弃':'Discarded','Mock环境':'Mock Environment'};
const tr=s=>ZH[String(s??'').trim()]??s;
const kids=pid=>D.filter(x=>String(x.parent_id)===String(pid)).sort((a,b)=>a.sort-b.sort);
const demote=(t,d)=>{let inF=false;return t.split('\n').map(l=>{if(/^\s*```/.test(l))inF=!inF;return(!inF&&/^#{1,6}\s/.test(l))?l.replace(/^#+/,m=>'#'.repeat(Math.min(6,d+m.length))):l}).join('\n')};
const esc=s=>String(s??'').replace(/\|/g,'\\|').replace(/\r?\n/g,' ');
const mark=Object.fromEntries(P.project.marks.map(m=>[m.mark_id,m.name]));
function table(params,cols){
  const ps=(params||[]).filter(p=>p.key && p.is_checked!==-1);
  if(!ps.length) return '';
  let o='| Name | Type | Required | Example | Description |\n|---|---|---|---|---|\n';
  for(const p of ps) o+=`| \`${esc(p.key)}\` | ${esc(p.field_type)} | ${p.not_null===1?'yes':'no'} | ${esc(String(p.value).slice(0,60))} | ${esc(tr(p.description))} |\n`;
  return o;
}
function fence(raw){ if(!raw||!raw.trim()) return ''; let s=raw.replace(/\r/g,''); let lang='';try{s=JSON.stringify(JSON.parse(s),null,2);lang='json'}catch(e){lang= s.trim().startsWith('{')?'jsonc':''} return '```'+lang+'\n'+s+'\n```\n'; }
let out='', toc='';
function api(a,depth){
  const r=a.request||{};
  let o=`${'#'.repeat(depth)} ${a.name}\n\n\`${a.method} ${a.url}\`  \n_Status: ${tr(mark[a.mark_id]||a.mark_id)} · Auth: ${r.auth?.type||'?'}_\n\n`;
  if(a.description?.trim()) o+=demote(a.description.replace(/\r/g,'').trim(),depth)+'\n\n';
  const sec=(t,ps)=>{const tb=table(ps); if(tb) o+=`**${t}**\n\n${tb}\n`;};
  sec('Headers',r.header?.parameter); sec('Path parameters',r.restful?.parameter); sec('Query parameters',r.query?.parameter); sec('Cookies',r.cookie?.parameter);
  const b=r.body||{};
  if(b.mode && b.mode!=='none'){ sec(`Body parameters (${b.mode})`, b.mode==='json'||b.mode==='xml'?b.raw_parameter:b.parameter); if(b.raw?.trim()){o+=`**Body example**\n\n`+fence(b.raw)+'\n';} }
  for(const ex of (a.response?.example||[])){
    const nm=tr(ex.expect?.name||'Response'); const code=ex.expect?.code||'';
    o+=`**Response — ${esc(nm)}${code?' ('+code+')':''}**\n\n`;
    const tb=table(ex.raw_parameter); if(tb) o+=tb+'\n';
    o+=fence(ex.raw)+'\n';
  }
  return o;
}
function walk(pid,depth){
  for(const n of kids(pid)){
    toc+=`${'  '.repeat(depth-2)}- ${n.target_type==='api'?'`'+n.method+'` ':''}${n.name}${n.target_type==='api'?' — `'+n.url.split('?')[0]+'`':''}\n`;
    if(n.target_type==='folder'){ out+=`${'#'.repeat(depth)} ${n.name}\n\n`; if(n.description?.trim()) out+=demote(n.description.trim(),depth)+'\n\n'; walk(n.target_id,depth+1); }
    else if(n.target_type==='doc'){ out+=`${'#'.repeat(depth)} ${n.name}\n\n${demote((n.description||'').replace(/\r/g,'').trim(),depth)}\n\n`; }
    else out+=api(n,depth);
  }
}
walk('0',2);
const head=`# Felicity Solar (fSolar) OpenAPI — Reference\n\nSource: https://docs.apipost.net/docs/detail/533ebd61e043000 (Apipost project "${P.project_name}", branch \`${P.branch_name}\`, last updated ${P.updated_at}).\nExtracted from the Apipost share API (\`/doc/preview\`, \`/doc/details\`). Content is reproduced as published (generated by \`tools/build-reference.js\`); see [REVIEW.md](REVIEW.md) for the problems found in it.\n\n**Environments listed in the share:** ${P.project.envs.map(e=>tr(e.name)+' → '+e.server_list.map(s=>s.uri).join(', ')).join('; ')}\n\n**Global parameters:** none · **Global auth:** ${P.project.global_param.auth.type} · **Global response codes:** ${P.project.codes.length||'none defined'}\n\n## Contents\n\n`;
fs.writeFileSync(outPath, head+toc+'\n'+out);
